        .output_out_1_IN  (bidir_in[1]),
        .output_out_1_OUT (bidir_out[1]),
        .output_out_2_IN  (bidir_in[2]),
        .output_out_2_OUT (bidir_out[2]),
        .output_out_3_IN  (bidir_in[3]),
        .output_out_3_OUT (bidir_out[3])
    );

    assign bidir_in = 4'b0000;


    always #5 clk = ~clk;
    reg [511:0] captured;
    integer capture_count = 0;
    integer passed_cases = 0;
    integer extra_internal_transfers = 0;

    always @(posedge clk) begin
        if (rst_n && dut.chip_core_internal_i.systolic_tx_two_done) begin
            if (capture_count < 128) begin
                captured = {captured[507:0], bidir_out};
                capture_count = capture_count + 1;
            end else begin
                // The current wrapper exposes only the first 128 nibbles.
                // Record continuing internal transfers separately; do not
                // mislabel them as additional externally valid result words.
                extra_internal_transfers = extra_internal_transfers + 1;
                if (bidir_out !== 4'b0000) $fatal(1, "Output not zero after wrapper result window");
            end
        end
    end

    task reset_dut;
        begin
            @(negedge clk);
            rst_n=0;
            input_in=0;
            captured=0;
            capture_count=0;
            repeat(3) @(posedge clk);
            @(negedge clk);
        end
    endtask

    task send_byte(input [7:0] val);
        begin
            @(negedge clk);
            input_in=val;
            rst_n=1;
            @(posedge clk);
        end
    endtask

    task send_packet(input [127:0] packet);
        integer k;
        begin
            for(k=15;k>=0;k=k-1) send_byte(packet[k*8 +: 8]);
            wait(dut.chip_core_internal_i.systolic_tx_one_done === 1'b1);
            @(posedge clk);
        end
    endtask

    task run_case(input [8*64-1:0] name, input [255:0] a, b, input [511:0] expected);
        integer r,c,k,errors;
        reg [127:0] packet;
        reg [31:0] got,want;
        begin
            reset_dut;
            for(r=0;r<4;r=r+1) begin
                packet[127:64]=a[255-r*64 -: 64];
                for(c=0;c<4;c=c+1) packet[63-c*16 -: 16]=b[255-(c*4+r)*16 -: 16];
                send_packet(packet);
            end
            wait(dut.chip_core_internal_i.systolic_done === 1'b1);
            #1;
            if(capture_count != 128) $fatal(1,"Incomplete result: %0d transfers",capture_count);
            errors=0;
            for(k=0;k<16;k=k+1) begin
                got=captured[511-k*32 -: 32];
                want=expected[511-k*32 -: 32];
                if(got !== want) begin
                    $display("MISMATCH %0s C[%0d,%0d] got=%h expected=%h",name,k/4,k%4,got,want);
                    errors=errors+1;
                end
            end
            if(errors) $fatal(1,"%0s failed: %0d elements",name,errors);
            passed_cases=passed_cases+1;
            $display("PASS: %0s (16 serialized result words)",name);
            repeat(3) @(negedge clk);
        end
    endtask

